"""Audit the mi250x-recipe-ops skill data against its authoritative recipe markdown.

Why this exists
---------------
The skill's `data/*.json` entries are **LLM-synthesised** from
`$AI/docs/recipes/**/*.md`: fields like `stack.notes`, `red_lines`,
`status_note` and `path_or_target` are prose that was written by reading the
markdown, not text a regular expression can lift out (verified empirically --
`rebuild`/`selfcheck` are condensed one-line commands, not raw code-block
lines). So the JSON must NOT be regenerated by a script: doing so would
overwrite hand-written synthesis with junk and silently drop fields.

What is actually missing is a **consistency gate**: when the markdown changes
and the JSON does not (the observed failure mode -- `data/*.json` still carries
`generated_at` from the last extraction), nothing notices. This script notices.

What it checks (all read-only)
------------------------------
1. every markdown file has a JSON entry with the same `id`, and vice versa;
2. frontmatter that maps verbatim to a JSON field agrees exactly
   (`status`, `verified`; `title_or_why` = `title` [+ " · "/"—" + `why`]);
3. every frontmatter `sources:` path exists on disk (catches renamed/deleted
   evidence a recipe still cites);
4. every frontmatter `consumers:` id resolves to a real arm in `data/arms.json`;
5. **claim drift**: for each JSON entry, which side mentions a topic keyword and
   which does not -- a keyword cited by the JSON but absent from the markdown is
   a field that was never written back into the authoritative source. Some of
   those are legitimately synthesised (by design), so the report separates them
   instead of failing.

Exit codes: 0 clean, 1 findings worth acting on, 2 unusable input.
"""

